"""App-scoped settings interpolation (${{ settings.KEY }}).

Settings are per-app, not framework-global: every *.graph.yaml lives under
apps/<app>/blueprint/ (see docs/DEV/BUILD/blueprint-schema-v2.2.md §6), and
an optional sibling apps/<app>/blueprint/settings.yaml is that app's single
source of truth for repeated literals (ports, etc.) referenced from any of
its graph.yaml files as ${{ settings.KEY }}. Two different apps' settings
never share a namespace or a file.

See docs/DEV/BUILD/refactoring-plan-v1.md §1.2 for the full design,
including why interpolating into the graph.yaml alone is not enough to avoid
LLM regeneration on a settings change (that's what config.py/config.ts,
generated by appgraph.build.files.write_settings_config, are for).
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

import yaml

from .exceptions import ToolFailed

_SETTINGS_TOKEN = re.compile(r"\$\{\{\s*settings\.([A-Za-z0-9_]+)\s*\}\}")

# Keyed by settings.yaml's resolved directory so multiple graph.yaml files
# in the same app's blueprint/ only trigger one read.
_settings_cache: dict[str, dict[str, Any]] = {}


def load_settings(graph_yaml_path: str | Path) -> dict[str, Any]:
    """Load the app-scoped settings.yaml sibling of the given graph.yaml.

    Returns {} (not an error) if no settings.yaml exists next to it —
    settings are opt-in per app.
    """
    directory = Path(graph_yaml_path).resolve().parent
    cache_key = str(directory)
    if cache_key in _settings_cache:
        return _settings_cache[cache_key]

    settings_path = directory / "settings.yaml"
    resolved: dict[str, Any] = {}
    if settings_path.exists():
        with settings_path.open(encoding="utf-8") as fh:
            raw = yaml.safe_load(fh) or {}
        for entry in raw.get("settings") or []:
            key = entry.get("key")
            if key:
                resolved[key] = entry.get("value")

    _settings_cache[cache_key] = resolved
    return resolved


def interpolate(obj: Any, settings: dict[str, Any]) -> Any:
    """Recursively resolve ${{ settings.KEY }} tokens anywhere inside obj.

    A string that is *exactly* one token (e.g. "${{ settings.PORT }}")
    resolves to the settings value's own type (so an int stays an int, which
    matters for callers like check_port_consistency() that compare resolved
    values directly). A token embedded in a larger string is stringified.

    Raises ToolFailed if a referenced key has no entry in settings — a typo'd
    key must never silently pass the literal "${{ ... }}" string through.
    """
    if isinstance(obj, str):
        full = _SETTINGS_TOKEN.fullmatch(obj.strip())
        if full:
            key = full.group(1)
            if key not in settings:
                raise ToolFailed(f"Unresolved settings reference: settings.{key}")
            return settings[key]

        def _replace(match: re.Match) -> str:
            key = match.group(1)
            if key not in settings:
                raise ToolFailed(f"Unresolved settings reference: settings.{key}")
            return str(settings[key])

        return _SETTINGS_TOKEN.sub(_replace, obj)
    if isinstance(obj, dict):
        return {k: interpolate(v, settings) for k, v in obj.items()}
    if isinstance(obj, list):
        return [interpolate(v, settings) for v in obj]
    return obj
